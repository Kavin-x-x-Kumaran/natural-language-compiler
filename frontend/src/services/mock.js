/**
 * Mock adapters, used ONLY when VITE_ENABLE_MOCK=true.
 *
 * Nothing in here talks to a model or a compiler. It exists so the terminal
 * and the interactive-input UI can be exercised without a backend. Every
 * status line it produces is prefixed "[mock]" and the generated C source
 * carries a loud comment on its first line.
 */

const MOCK_SOURCE = `/* MOCK OUTPUT: not generated by the model */
#include <stdio.h>

int main(void) {
    int a = 0, b = 0;
    printf("Enter two numbers: ");
    if (scanf("%d %d", &a, &b) != 2) {
        fprintf(stderr, "invalid input\\n");
        return 1;
    }
    printf("Sum: %d\\n", a + b);
    return 0;
}
`;

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** Simulated generation. Resolves with the code string returned by the real adapter. */
export async function mockGenerate(payload, { signal } = {}) {
  await delay(1000);
  if (signal && signal.aborted) {
    const error = new Error('Aborted');
    error.name = 'AbortError';
    throw error;
  }
  const lines = Array.isArray(payload) ? payload : [];
  return `${MOCK_SOURCE}/* [mock] ${lines.length} natural-language line(s) received */\n`;
}

/**
 * Simulated execution. Mirrors the websocket adapter's handle so `useCompiler`
 * cannot tell them apart.
 */
export function mockStartRun({ onEvent, onClose } = {}) {
  let stopped = false;
  let closed = false;
  const timers = [];

  const emit = (event) => {
    if (stopped || closed) return;
    onEvent?.(event);
  };
  const at = (ms, fn) => timers.push(setTimeout(fn, ms));
  const clearTimers = () => {
    timers.forEach(clearTimeout);
    timers.length = 0;
  };

  at(150, () => emit({ type: 'status', state: 'compiling' }));
  at(700, () => emit({ type: 'status', state: 'running' }));
  at(900, () => emit({ type: 'stdout', data: '[mock] Enter two numbers: ' }));
  at(950, () => emit({ type: 'input_required' }));

  return {
    sendInput(text) {
      if (stopped || closed) return;
      const trimmed = String(text).trim();
      at(200, () =>
        emit({ type: 'stdout', data: `[mock] Sum of "${trimmed}" is a simulated value\n` })
      );
      at(450, () => emit({ type: 'exit', code: 0, phase: 'run' }));
    },
    stop() {
      if (stopped || closed) return;
      stopped = true;
      clearTimers();
      setTimeout(() => {
        stopped = false;
        emit({ type: 'exit', code: 143, phase: 'run' });
        closed = true;
        onClose?.({ code: 1000, reason: 'mock stop' });
      }, 200);
    },
    close() {
      if (closed) return;
      closed = true;
      clearTimers();
    },
    isMock: true,
  };
}
